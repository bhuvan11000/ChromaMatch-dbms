-- ===========================================================================
-- ChromaMatch — course DDL demonstration
-- ===========================================================================
-- Source: docs/ChromaMatch_Database_Design.md §9–10 and
--         docs/ChromaMatch_Architecture.md §5.8.2.
--
-- This is a course deliverable, NOT an application migration. It never touches
-- the public/app schema: everything happens inside the scratch schema
-- cm_ddl_demo, and the final ROLLBACK removes the scratch schema again.
--
-- What it demonstrates:
--   CREATE  table (with PK, UNIQUE, FK, CHECK and defaults)
--   ALTER   add column, add constraint, rename column, rename table
--   CREATE  index
--   DROP    index, column, table
--
-- Run it with psql (the local Docker database):
--   psql "$DATABASE_URL_DIRECT" -v ON_ERROR_STOP=1 -f scripts/ddl-demo.sql
--
-- Re-running is safe: the transaction rolls back, so no demo object survives.
-- ===========================================================================

BEGIN;

DROP SCHEMA IF EXISTS cm_ddl_demo CASCADE;
CREATE SCHEMA cm_ddl_demo;
SET LOCAL search_path TO cm_ddl_demo, pg_catalog;

-- ---------------------------------------------------------------------------
-- 1. CREATE — two related tables with the usual table-level constraints.
-- ---------------------------------------------------------------------------
CREATE TABLE demo_players (
  player_id bigint GENERATED BY DEFAULT AS IDENTITY,
  username varchar(30) NOT NULL,
  email varchar(255) NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT demo_players_pkey PRIMARY KEY (player_id),
  CONSTRAINT demo_players_username_key UNIQUE (username)
);

CREATE TABLE demo_rooms (
  room_id bigint GENERATED BY DEFAULT AS IDENTITY,
  room_code varchar(8) NOT NULL,
  host_id bigint NOT NULL,
  status varchar(12) NOT NULL DEFAULT 'lobby',
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT demo_rooms_pkey PRIMARY KEY (room_id),
  CONSTRAINT demo_rooms_room_code_key UNIQUE (room_code),
  CONSTRAINT demo_rooms_host_fk FOREIGN KEY (host_id)
    REFERENCES demo_players (player_id) ON DELETE RESTRICT,
  CONSTRAINT demo_rooms_status_check
    CHECK (status IN ('lobby', 'in_progress', 'finished', 'cancelled'))
);

-- Seed one row so the later ADD COLUMN / DROP COLUMN steps operate on data.
INSERT INTO demo_players (username, email)
VALUES ('ada', 'ada@example.com');

INSERT INTO demo_rooms (room_code, host_id)
SELECT 'DEMO01', player_id
FROM demo_players
WHERE username = 'ada';

-- ---------------------------------------------------------------------------
-- 2. ALTER TABLE … ADD COLUMN
-- ---------------------------------------------------------------------------
ALTER TABLE demo_players
  ADD COLUMN display_name varchar(40);

UPDATE demo_players
SET display_name = 'Ada'
WHERE username = 'ada';

-- ---------------------------------------------------------------------------
-- 3. ALTER TABLE … ADD CONSTRAINT
-- ---------------------------------------------------------------------------
ALTER TABLE demo_players
  ADD CONSTRAINT demo_players_display_name_check
  CHECK (display_name IS NULL OR length(display_name) BETWEEN 1 AND 40);

-- ---------------------------------------------------------------------------
-- 4. ALTER TABLE … RENAME COLUMN
-- ---------------------------------------------------------------------------
ALTER TABLE demo_players
  RENAME COLUMN display_name TO handle;

-- ---------------------------------------------------------------------------
-- 5. ALTER TABLE … RENAME TABLE (a second rename form)
-- ---------------------------------------------------------------------------
ALTER TABLE demo_rooms
  RENAME TO demo_game_rooms;

-- ---------------------------------------------------------------------------
-- 6. CREATE INDEX … then DROP INDEX
-- ---------------------------------------------------------------------------
CREATE INDEX demo_game_rooms_status_idx
  ON demo_game_rooms (status);

DROP INDEX demo_game_rooms_status_idx;

-- ---------------------------------------------------------------------------
-- 7. ALTER TABLE … DROP COLUMN
-- ---------------------------------------------------------------------------
ALTER TABLE demo_players
  DROP COLUMN handle;

-- ---------------------------------------------------------------------------
-- 8. DROP TABLE — child first because demo_game_rooms references demo_players.
-- ---------------------------------------------------------------------------
DROP TABLE demo_game_rooms;
DROP TABLE demo_players;

-- ---------------------------------------------------------------------------
-- 9. Roll back: the public schema and the database are exactly as before.
-- ---------------------------------------------------------------------------
ROLLBACK;
